#!/usr/bin/env python3
"""Generate the README asset inventory from the assets themselves.

The inventory used to be hand-typed. It drifted: a new global rule landed
2026-08-26 and first appeared in the README tree on 2026-08-31, and the
"跑完就有 …" line still said 4 global rules / 2 hooks when the registry held 6
and 4. That is exactly the failure this kit's own rule names — a second copy of
a fact, and the copy the reader sees is the one that rots.

So: one derived block, regenerated by `kit docs-sync`, gated by
`kit docs-sync --check` in the test suite. Each asset carries its own one-liner:

  rules   `<!-- claude-kit rule · <name> — <summary> -->` on line 1
  hooks   a `# kit-summary: <summary>` line in the header comment
  skills  frontmatter `description:`, truncated to its first sentence
  agents  same as skills

A missing summary is an error, not a blank cell — a blank cell is how a rule
ends up in the tree with nobody able to say what it is for.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN GENERATED: kit inventory · `kit docs-sync` -->"
END = "<!-- END GENERATED: kit inventory -->"

# Codex representation of each logical asset. Mirrors lib/assets.sh
# codex_skill_source / codex_agent_source; test-docs-sync.sh asserts they agree,
# so this stays a projection rather than a second opinion.
CODEX_SKILL_SKIP = {"memory-audit", "skill-creator"}


def die(msg: str) -> "NoReturn":  # type: ignore[valid-type]
    print(f"docs-sync: {msg}", file=sys.stderr)
    sys.exit(2)


def first_sentence(text: str, limit: int = 90) -> str:
    """A skill/agent one-liner is DERIVED from its frontmatter description, never
    a second hand-written copy — the description is what the router actually reads."""
    text = " ".join(text.split())
    cut = min((i for i in (text.find(s) for s in (". ", "。", " — ", "; ", " (")) if 0 < i < limit),
              default=None)
    if cut is not None:
        return text[:cut].rstrip(" .;,")
    if len(text) <= limit:
        return text
    # rfind returns -1 when there is no space inside the limit — a long CJK summary
    # has none — and text[:-1] then drops ONE character instead of truncating.
    cut = text.rfind(" ", 0, limit)
    return text[:cut if cut > 0 else limit].rstrip(" .;,") + "…"


def rule_summary(path: Path) -> str:
    head = path.read_text(encoding="utf-8").splitlines()[:1]
    m = re.match(r"<!--\s*claude-kit (?:rule|reference)\s*·\s*([\w.-]+)\s*(?:—\s*(.*?))?\s*-->",
                 head[0] if head else "")
    if not m:
        die(f"{path}: line 1 must be `<!-- claude-kit rule|reference · {path.stem} — <summary> -->`")
    if m.group(1) != path.stem:
        die(f"{path}: header names '{m.group(1)}' but the file is '{path.stem}'")
    summary = (m.group(2) or "").strip()
    if not summary:
        die(f"{path}: header has no `— <summary>` part")
    return summary


def hook_summary(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines()[:15]:
        m = re.match(r"\s*#\s*kit-summary:\s*(.+)", line)
        if m:
            return m.group(1).strip()
    die(f"{path}: no `# kit-summary: …` line in the first 15 lines")


def frontmatter_summary(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        die(f"{path}: no YAML frontmatter")
    body = text.split("---", 2)[1]
    m = re.search(r"^description:\s*(.*)$", body, re.M)
    if not m:
        die(f"{path}: frontmatter has no description")
    desc = m.group(1).strip()
    if desc.startswith(("'", '"')):
        quote = desc[0]
        rest = body[m.end():]
        desc = desc[1:]
        if quote not in desc:
            desc = desc + " " + rest.split(quote, 1)[0]
        else:
            desc = desc.split(quote, 1)[0]
        desc = desc.replace(quote * 2, quote)
    return first_sentence(desc)


def build(kit: Path) -> str:
    g = sorted((kit / "rules" / "global").glob("*.md"))
    o = sorted((kit / "rules" / "optin").glob("*.md"))
    skills = sorted(d for d in (kit / "skills").iterdir() if (d / "SKILL.md").is_file())
    agents = sorted((kit / "agents").glob("*.md"))
    hooks = sorted(p for p in (kit / "hooks").iterdir() if p.is_file())
    suites = sorted((kit / "tests").glob("test-*.sh"))

    codex_skills = [d for d in skills if d.name not in CODEX_SKILL_SKIP]
    resident = sum(p.stat().st_size for p in g)

    L = [BEGIN, ""]
    L.append(
        f"安装后 **Claude 端**：{len(g)} 条常驻规则 · {len(skills)} 个 skill · "
        f"{len(agents)} 个 agent · {len(hooks_logical(kit))} 个 hook。"
    )
    L.append(
        f"**Codex 端**：同 {len(g)} 条规则 · {len(codex_skills)} 个 skill · "
        f"{len(agents)} 个 agent（hook 注册形状见 [`docs/CODEX.md`](docs/CODEX.md)）。"
    )
    L.append(f"回归测试 {len(suites)} 套。")
    L.append("")
    L.append(
        f"**`rules/global/`** — 常驻内核，同一正文到达两个宿主及子 agent。"
        f"实测 {resident:,} 字节，每个 session 和每个 subagent 都吃。"
    )
    for p in g:
        L.append(f"- `{p.stem}` — {rule_summary(p)}")
    L.append("")
    L.append("**`rules/optin/`** — 默认关；`kit add` 按项目、`kit config on` 按机器。")
    for p in o:
        L.append(f"- `{p.stem}` — {rule_summary(p)}")
    refs = sorted((kit / "references").glob("*.md")) if (kit / "references").is_dir() else []
    if refs:
        L.append("")
        L.append("**`references/`** — **不常驻**。规则里只留一行指针，遇到那类问题才 page in。")
        for p in refs:
            L.append(f"- `{p.name}` — {rule_summary(p)}")
    L.append("")
    L.append("**`skills/`** — 全局 skill（★ = Codex 端也装）。")
    for d in skills:
        star = "★ " if d.name not in CODEX_SKILL_SKIP else "  "
        L.append(f"- {star}`{d.name}` — {frontmatter_summary(d / 'SKILL.md')}")
    L.append("")
    L.append("**`agents/`** — 全局委派角色；纪律从 rules 继承，不手抄。")
    for p in agents:
        L.append(f"- `{p.stem}` — {frontmatter_summary(p)}")
    L.append("")
    L.append("**`hooks/`** — 规则说不动的那几件，交给闸。")
    for name, p in hooks_logical(kit).items():
        L.append(f"- `{name}` — {hook_summary(p)}")
    L.append("")
    L.append(END)
    return "\n".join(L)


def hooks_logical(kit: Path) -> "dict[str, Path]":
    """The logical hook assets, in lib/assets.sh's order. Host adapters
    (codex-*.sh) are implementation details of the same logical hook."""
    out = {}
    for name in ("git-guard", "instructions-loaded", "wrap-up-trigger", "gotchas-contract"):
        for ext in (".sh", ".py"):
            p = kit / "hooks" / f"{name}{ext}"
            if p.is_file():
                out[name] = p
                break
        else:
            die(f"hooks/{name}.(sh|py) missing but listed in the logical hook set")
    return out


def main() -> None:
    kit = Path(__file__).resolve().parent.parent
    readme = kit / "README.zh.md"
    check = "--check" in sys.argv[1:]
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        die(f"README.zh.md has no generated block; add the {BEGIN} / {END} markers")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    new = pre + build(kit) + post
    if new == text:
        print("docs-sync: README inventory is in sync")
        return
    if check:
        print("docs-sync: README inventory is STALE — run `kit docs-sync`", file=sys.stderr)
        import difflib

        old_block = BEGIN + rest.split(END, 1)[0] + END
        sys.stderr.writelines(
            difflib.unified_diff(
                old_block.splitlines(True), build(kit).splitlines(True),
                fromfile="README (committed)", tofile="README (derived)",
            )
        )
        sys.exit(1)
    readme.write_text(new, encoding="utf-8")
    print("docs-sync: README inventory rewritten")


if __name__ == "__main__":
    main()
